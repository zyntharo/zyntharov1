"""Plugin loading, installation, scaffolding and hot reload.

The interesting case for this product is the *self-extension* case: an agent
decides it needs a capability it does not have, writes the code, installs it
and immediately uses it. :meth:`PluginManager.scaffold_and_install` supports
that flow - it takes generated Python plus a manifest, validates it, writes it
into the plugin directory, imports it in-process and registers its tools, all
without a restart.

Every install is: permission-gated, digest-recorded, import-error-reported (a
broken plugin never takes down the runtime) and reversible.
"""

from __future__ import annotations

import importlib.util
import json
import logging
import shutil
import sys
import textwrap
import time
from pathlib import Path
from typing import Any, Sequence

from ..bus import BUS, EventType
from .sdk import LoadedPlugin, PluginAPI, PluginManifest, digest_directory

log = logging.getLogger("vyralis.plugins.loader")

MANIFEST_NAME = "plugin.json"

TEMPLATE_MANIFEST = {
    "id": "example_plugin",
    "name": "Example Plugin",
    "version": "0.1.0",
    "description": "What this plugin does and when the agent should use it.",
    "author": "Vyralis",
    "entrypoint": "plugin.py",
    "category": "plugin",
    "tools": [],
    "permissions": ["safe"],
    "requires": [],
}

TEMPLATE_CODE = '''"""{{name}} - generated by Vyralis.

Templates are given to the coding model on first use; after that the plugin's
own memory and past versions are the reference. Keep the register() contract.
"""

from __future__ import annotations

from typing import Any


def register(api) -> None:
    """Called once when the plugin loads. Register tools here."""

    @api.tool(
        "{{tool_name}}",
        "{{tool_description}}",
        {
            "type": "object",
            "properties": {
                "input": {"type": "string", "description": "What to act on."}
            },
            "required": ["input"],
            "additionalProperties": False,
        },
    )
    def {{tool_name}}(input: str, ctx: Any = None) -> dict[str, Any]:
        # Use api.call("files.read", path=...) to reuse existing capabilities,
        # api.http() for network calls, api.remember() to persist what you learn.
        return {"ok": True, "input": input}
'''


class PluginManager:
    """Discovers, loads, installs and unloads plugins."""

    def __init__(self, *, registry: Any, settings: Any, paths: Any, store: Any,
                 bus: Any = BUS) -> None:
        self.registry = registry
        self.settings = settings
        self.paths = paths
        self.store = store
        self.bus = bus
        self.loaded: dict[str, LoadedPlugin] = {}
        self.paths.plugins.mkdir(parents=True, exist_ok=True)

    # -- discovery ------------------------------------------------------
    def discover(self) -> list[Path]:
        found: list[Path] = []
        for child in sorted(self.paths.plugins.iterdir()):
            if child.is_dir() and (child / MANIFEST_NAME).exists():
                found.append(child)
        return found

    def _read_manifest(self, directory: Path) -> PluginManifest:
        raw = json.loads((directory / MANIFEST_NAME).read_text("utf-8"))
        manifest = PluginManifest.from_dict(raw, fallback_id=directory.name)
        if not manifest.id:
            raise ValueError(f"{directory.name}: manifest has no id")
        manifest.id = _safe_id(manifest.id)
        return manifest

    # -- loading --------------------------------------------------------
    def load_all(self) -> list[dict[str, Any]]:
        results = []
        for directory in self.discover():
            results.append(self.load(directory).to_json())
        return results

    def load(self, directory: Path) -> LoadedPlugin:
        directory = Path(directory)
        try:
            manifest = self._read_manifest(directory)
        except Exception as exc:  # noqa: BLE001
            plugin = LoadedPlugin(
                manifest=PluginManifest(id=directory.name, name=directory.name),
                path=directory, error=f"invalid manifest: {exc}",
            )
            self.store.upsert_plugin(plugin.manifest.id, plugin.manifest.name, "0",
                                     str(directory), {}, "error", plugin.error)
            return plugin

        entrypoint = directory / manifest.entrypoint
        if not entrypoint.exists():
            plugin = LoadedPlugin(manifest=manifest, path=directory,
                                  error=f"entrypoint '{manifest.entrypoint}' is missing")
            self.store.upsert_plugin(manifest.id, manifest.name, manifest.version,
                                     str(directory), manifest.to_dict(), "error", plugin.error)
            return plugin

        # Unload a previous version first so reloads are clean.
        self.unload(manifest.id, quiet=True)

        module_name = f"vyralis_plugin_{manifest.id}"
        try:
            spec = importlib.util.spec_from_file_location(module_name, entrypoint)
            if spec is None or spec.loader is None:
                raise ImportError(f"could not build an import spec for {entrypoint}")
            module = importlib.util.module_from_spec(spec)
            sys.modules[module_name] = module
            spec.loader.exec_module(module)

            api = PluginAPI(
                manifest, self.registry, settings=self.settings, paths=self.paths,
                store=self.store, bus=self.bus, data_dir=self.paths.plugin_cache / manifest.id,
            )
            api.data_dir.mkdir(parents=True, exist_ok=True)

            register = getattr(module, "register", None)
            if callable(register):
                register(api)
            elif hasattr(module, "PLUGIN"):
                module.PLUGIN.register(api)  # type: ignore[union-attr]
            else:
                raise AttributeError(
                    f"{entrypoint.name} must define register(api) or a PLUGIN object with .register(api)"
                )

            digest = digest_directory(directory)
            plugin = LoadedPlugin(manifest=manifest, path=directory, module=module,
                                  tools=api.registered_tools, digest=digest)
            self.loaded[manifest.id] = plugin
            self.store.upsert_plugin(manifest.id, manifest.name, manifest.version,
                                     str(directory), manifest.to_dict() | {"tools": plugin.tools},
                                     "loaded")
            self.bus.publish(EventType.PLUGIN_LOADED, plugin.to_json())
            log.info("loaded plugin %s with %d tool(s)", manifest.id, len(plugin.tools))
            return plugin
        except Exception as exc:  # noqa: BLE001
            error = f"{type(exc).__name__}: {exc}"
            log.warning("plugin %s failed to load: %s", manifest.id, error)
            plugin = LoadedPlugin(manifest=manifest, path=directory, error=error)
            self.store.upsert_plugin(manifest.id, manifest.name, manifest.version,
                                     str(directory), manifest.to_dict(), "error", error)
            self.bus.publish(EventType.PLUGIN_ERROR, {"id": manifest.id, "error": error})
            return plugin

    def unload(self, plugin_id: str, *, quiet: bool = False) -> bool:
        plugin = self.loaded.pop(plugin_id, None)
        module_name = f"vyralis_plugin_{plugin_id}"
        module = sys.modules.pop(module_name, None)
        if module is not None:
            for name in list(sys.modules):
                if name.startswith(f"{module_name}."):
                    sys.modules.pop(name, None)
        # Tools may be registered under the plugin id namespace.
        removed = self.registry.unregister_prefix(f"{plugin_id}.")
        if not quiet and (plugin or removed):
            self.bus.publish(EventType.PLUGIN_LOADED, {"id": plugin_id, "status": "unloaded",
                                                       "tools_removed": removed})
        return bool(plugin or removed)

    def reload(self, plugin_id: str) -> dict[str, Any]:
        plugin = self.loaded.get(plugin_id)
        directory = plugin.path if plugin else next(
            (path for path in self.discover() if path.name == plugin_id), None
        )
        if directory is None:
            raise FileNotFoundError(f"No plugin with id '{plugin_id}'.")
        self.unload(plugin_id, quiet=True)
        return self.load(directory).to_json()

    # -- installation ---------------------------------------------------
    def install(self, source: Path, *, trusted: bool = False) -> dict[str, Any]:
        """Copy a plugin folder into the plugin directory and load it."""
        source = Path(source)
        if not (source / MANIFEST_NAME).exists():
            raise FileNotFoundError(f"{source} has no {MANIFEST_NAME}.")
        manifest = self._read_manifest(source)
        manifest.trusted = trusted
        destination = self.paths.plugins / manifest.id
        if destination.exists():
            shutil.rmtree(destination)
        shutil.copytree(source, destination)
        (destination / MANIFEST_NAME).write_text(json.dumps(manifest.to_dict(), indent=2), "utf-8")
        plugin = self.load(destination)
        payload = plugin.to_json()
        self.bus.publish(EventType.PLUGIN_INSTALLED, payload)
        return payload

    def scaffold_and_install(
        self, plugin_id: str, code: str, *, name: str | None = None,
        description: str = "", tools: Sequence[str] = (), generated: bool = True,
        validate_only: bool = False,
    ) -> dict[str, Any]:
        """The self-extension path: generated code becomes a live capability."""
        plugin_id = _safe_id(plugin_id)
        if validate_only:
            return self.validate(code, plugin_id=plugin_id)

        directory = self.paths.plugins / plugin_id
        directory.mkdir(parents=True, exist_ok=True)
        entrypoint = directory / "plugin.py"
        entrypoint.write_text(code, "utf-8")
        manifest = PluginManifest(
            id=plugin_id, name=name or plugin_id.replace("_", " ").title(),
            description=description or "Runtime-generated Vyralis plugin.",
            tools=list(tools), generated=generated, trusted=generated,
        )
        (directory / MANIFEST_NAME).write_text(json.dumps(manifest.to_dict(), indent=2), "utf-8")
        (directory / "README.md").write_text(
            f"# {manifest.name}\n\n{manifest.description}\n\n"
            f"Generated by Vyralis at {time.strftime('%Y-%m-%d %H:%M')}.\n",
            "utf-8",
        )
        plugin = self.load(directory)
        payload = plugin.to_json()
        self.bus.publish(EventType.PLUGIN_INSTALLED, payload)
        return payload

    def validate(self, code: str, *, plugin_id: str = "generated_plugin") -> dict[str, Any]:
        """Syntax-check and smoke-load generated code in a throwaway registry."""
        import ast

        report: dict[str, Any] = {"id": plugin_id, "valid": False, "errors": [], "tools": []}
        try:
            tree = ast.parse(code)
        except SyntaxError as exc:
            report["errors"].append(f"SyntaxError at line {exc.lineno}: {exc.msg}")
            return report

        functions = {node.name for node in ast.walk(tree) if isinstance(node, ast.FunctionDef)}
        if "register" not in functions:
            report["errors"].append("Generated code must define register(api).")

        # Detect tools statically so the manifest can advertise them.
        for node in ast.walk(tree):
            if isinstance(node, ast.Call) and getattr(node.func, "attr", "") == "tool":
                if node.args and isinstance(node.args[0], ast.Constant):
                    report["tools"].append(str(node.args[0].value))

        banned = {"subprocess.Popen", "os.system", "eval", "exec", "compile", "__import__"}
        for name in banned:
            if name in code:
                report.setdefault("warnings", []).append(
                    f"generated code references {name} - review before trusting it"
                )
        report["valid"] = not report["errors"]
        return report

    def uninstall(self, plugin_id: str) -> dict[str, Any]:
        plugin_id = _safe_id(plugin_id)
        self.unload(plugin_id)
        directory = self.paths.plugins / plugin_id
        if directory.exists():
            shutil.rmtree(directory)
        shutil.rmtree(self.paths.plugin_cache / plugin_id, ignore_errors=True)
        self.store.remove_plugin(plugin_id)
        return {"id": plugin_id, "uninstalled": True}

    # -- scaffolding ----------------------------------------------------
    def write_template(self, destination: Path, *, plugin_id: str, name: str,
                       description: str, tool_name: str = "do_thing",
                       tool_description: str = "Describe what this tool does.") -> Path:
        """Create a ready-to-edit plugin folder from the shipped template.

        The template on disk is the single source of truth (so the file the agent
        reads is the file that gets copied); :data:`TEMPLATE_CODE` is only the
        fallback for a frozen build that lost its data files.
        """
        destination = Path(destination) / _safe_id(plugin_id)
        destination.mkdir(parents=True, exist_ok=True)
        manifest = dict(TEMPLATE_MANIFEST)
        manifest.update({"id": _safe_id(plugin_id), "name": name, "description": description,
                         "tools": [f"{_safe_id(plugin_id)}.{tool_name}"]})
        (destination / MANIFEST_NAME).write_text(json.dumps(manifest, indent=2), "utf-8")
        (destination / "plugin.py").write_text(
            self.template_source()
            .replace("{{name}}", name)
            .replace("{{tool_name}}", tool_name)
            .replace("{{tool_description}}", tool_description),
            "utf-8",
        )
        (destination / "README.md").write_text(
            textwrap.dedent(f"""\
                # {name}

                {description}

                ## Layout
                - `plugin.json` - manifest (id, tools, permissions).
                - `plugin.py`  - `register(api)` defines tools with `@api.tool(...)`.

                ## Notes
                Call other capabilities with `api.call("files.read", path=...)`; that path goes
                through the normal permission checks.
                """),
            "utf-8",
        )
        return destination

    @staticmethod
    def template_source() -> str:
        """Read the shipped plugin template, falling back to the embedded copy."""
        from ..config import package_dir

        path = package_dir() / "templates" / "plugin_template" / "plugin.py"
        try:
            return path.read_text("utf-8")
        except OSError:
            return TEMPLATE_CODE

    # -- reporting ------------------------------------------------------
    def status(self) -> list[dict[str, Any]]:
        rows = {entry["id"]: entry for entry in self.store.list_plugins()}
        for plugin_id, plugin in self.loaded.items():
            rows.setdefault(plugin_id, plugin.to_json())
            rows[plugin_id] = plugin.to_json()
        return list(rows.values())


def _safe_id(value: str) -> str:
    cleaned = "".join(ch if ch.isalnum() or ch in "_-" else "_" for ch in value.strip().lower())
    return cleaned.strip("_") or "plugin"
